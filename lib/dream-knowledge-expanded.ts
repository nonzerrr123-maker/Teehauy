function stableDigits(id: string, groupIndex: number, itemIndex: number): readonly [string, string, string] {
  let value = 2166136261;
  for (const character of id) {
    value ^= character.codePointAt(0) ?? 0;
    value = Math.imul(value, 16777619) >>> 0;
  }
  const first = (value + groupIndex * 3 + itemIndex) % 10;
  const second = (Math.floor(value / 10) + groupIndex + itemIndex * 3) % 10;
  const third = (Math.floor(value / 100) + groupIndex * 7 + itemIndex * 5) % 10;
  return [`${first}`, `${second}`, `${third}`];
}

